"""Generate the Rust language and duration tables from the engine's Python modules.

Developer tool. It reads `omnivoice/utils/lang_map.py` and `omnivoice/utils/duration.py`
from the engine's virtual environment and writes `crates/jeuvoice-omnivoice/src/lang.rs`
and `crates/jeuvoice-omnivoice/src/duration_table.rs`.

    engine\\.venv\\Scripts\\python.exe -I tools\\reference\\gen_tables.py
"""

from __future__ import annotations

import ast
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SITE = ROOT / "engine/.venv/Lib/site-packages/omnivoice/utils"
OUT = ROOT / "crates/jeuvoice-omnivoice/src"


def literal(path: Path, name: str) -> object:
    """The value of a module level assignment `name = <literal>`."""
    tree = ast.parse(path.read_text(encoding="utf-8"))
    for node in tree.body:
        if isinstance(node, ast.Assign) and any(
            isinstance(t, ast.Name) and t.id == name for t in node.targets
        ):
            return ast.literal_eval(node.value)
    raise SystemExit(f"{path}: no {name}")


def write_lang() -> None:
    pairs = literal(SITE / "lang_map.py", "LANG_NAME_TO_ID")
    rows = sorted(pairs.items())
    lines = [
        "//! The language names and ISO 639-3 codes of the engine (`omnivoice/utils/lang_map.py`).",
        "//! Generated by `tools/reference/gen_tables.py`; do not edit by hand.",
        "",
        "/// Every `(lowercase name, code)` pair, sorted by name.",
        "const NAMES: &[(&str, &str)] = &[",
    ]
    for name, code in rows:
        lines.append(f'    ({rust_str(name)}, {rust_str(code)}),')
    lines += [
        "];",
        "",
        "/// The code of a language name or a code itself, as `_resolve_language` accepts it: a code",
        "/// matches exactly, a name ignores case. `None` means the model does not know the language.",
        "pub fn code_of(input: &str) -> Option<&'static str> {",
        "    let raw = input.trim();",
        "    if let Some((_, code)) = NAMES.iter().find(|(_, code)| *code == raw) {",
        "        return Some(code);",
        "    }",
        "    let key = raw.to_lowercase();",
        "    NAMES",
        "        .binary_search_by(|(name, _)| name.cmp(&key.as_str()))",
        "        .ok()",
        "        .map(|i| NAMES[i].1)",
        "}",
        "",
        "/// The number of languages the model lists.",
        "pub fn count() -> usize {",
        "    NAMES.len()",
        "}",
        "",
    ]
    (OUT / "lang.rs").write_text("\n".join(lines), encoding="utf-8", newline="\n")


def write_duration() -> None:
    tree = ast.parse((SITE / "duration.py").read_text(encoding="utf-8"))
    ranges = weights = None
    for node in ast.walk(tree):
        if isinstance(node, ast.Assign) and any(
            isinstance(t, ast.Attribute) and t.attr == "ranges" for t in node.targets
        ):
            ranges = ast.literal_eval(node.value)
        if isinstance(node, ast.Assign) and any(
            isinstance(t, ast.Attribute) and t.attr == "weights" for t in node.targets
        ):
            weights = ast.literal_eval(node.value)
    if ranges is None or weights is None:
        raise SystemExit("duration.py: no ranges or weights")

    lines = [
        "//! The tables of `RuleDurationEstimator` (`omnivoice/utils/duration.py`, lines 34 to",
        "//! 190). Generated by `tools/reference/gen_tables.py`; do not edit by hand.",
        "",
        "/// The weight of a script, relative to one Latin letter.",
        "pub fn weight_of(script: &str) -> f64 {",
        "    match script {",
    ]
    for key, value in sorted(weights.items()):
        lines.append(f"        {rust_str(key)} => {value!r},")
    lines += [
        '        _ => 1.0,',
        "    }",
        "}",
        "",
        "/// `(end code point, script)`, sorted: the script of a code point is the first entry",
        "/// whose end is not below it.",
        "pub const RANGES: &[(u32, &str)] = &[",
    ]
    for end, name in ranges:
        lines.append(f"    (0x{end:04X}, {rust_str(name)}),")
    lines += ["];", ""]
    (OUT / "duration_table.rs").write_text("\n".join(lines), encoding="utf-8", newline="\n")


def rust_str(s: str) -> str:
    out = s.replace("\\", "\\\\").replace('"', '\\"')
    return f'"{out}"'


def main() -> None:
    write_lang()
    write_duration()
    print(f"wrote {OUT / 'lang.rs'} and {OUT / 'duration_table.rs'}")


if __name__ == "__main__":
    main()
